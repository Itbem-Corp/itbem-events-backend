\set ON_ERROR_STOP on

-- Run only in a disposable database whose name starts with
-- eventi_wall_bench_. The script drops and recreates public.moments.
DO $$
BEGIN
    IF current_database() !~ '^eventi_wall_bench_' THEN
        RAISE EXCEPTION 'refusing to benchmark in non-scratch database %', current_database();
    END IF;
END
$$;

DROP TABLE IF EXISTS moments;
CREATE TABLE moments (
    id uuid PRIMARY KEY,
    invitation_id uuid,
    moment_type_id uuid,
    guest_id uuid,
    title text,
    description text,
    content_url text,
    is_approved boolean DEFAULT false,
    "order" bigint,
    created_at timestamptz,
    updated_at timestamptz,
    deleted_at timestamptz,
    event_id uuid,
    content_type varchar(100) DEFAULT '',
    processing_status varchar(20) DEFAULT '',
    processing_duration_ms bigint DEFAULT 0,
    original_size_bytes bigint DEFAULT 0,
    optimized_size_bytes bigint DEFAULT 0,
    error_message varchar(500) DEFAULT '',
    thumbnail_url varchar(500) DEFAULT ''
);

-- Baseline indexes generated by the current model tags.
CREATE INDEX idx_moments_deleted_at ON moments (deleted_at);
CREATE INDEX idx_moments_event_id ON moments (event_id);
CREATE INDEX idx_moments_invitation_id ON moments (invitation_id);
CREATE INDEX idx_moments_moment_type_id ON moments (moment_type_id);

INSERT INTO moments (
    id, title, description, content_url, is_approved, "order",
    created_at, updated_at, deleted_at, event_id, content_type,
    processing_status, processing_duration_ms, original_size_bytes,
    optimized_size_bytes, error_message, thumbnail_url
)
SELECT
    md5('moment-' || g)::uuid,
    'Momento ' || g,
    repeat('Recuerdo compartido ', 4),
    'moments/' || (g % 37) || '/optimized/' || g || '.webp',
    (g % 10) < 7,
    CASE WHEN g % 11 = 0 THEN (g % 5000) + 1 ELSE 0 END,
    timestamptz '2025-01-01 00:00:00+00' + g * interval '1 second',
    timestamptz '2025-01-01 00:00:00+00' + g * interval '1 second'
        + (g % 300) * interval '1 second',
    CASE
        WHEN g % 97 = 0
        THEN timestamptz '2025-01-01 00:00:00+00'
            + g * interval '1 second' + interval '1 day'
        ELSE NULL
    END,
    md5('event-' || (g % 37))::uuid,
    'image/webp',
    CASE
        WHEN g % 13 < 5 THEN ''
        WHEN g % 13 < 9 THEN 'done'
        WHEN g % 13 = 9 THEN 'pending'
        WHEN g % 13 = 10 THEN 'processing'
        ELSE 'failed'
    END,
    250, 2500000, 350000, '', ''
FROM generate_series(1, 600000) AS g;

VACUUM (ANALYZE, FREEZE) moments;
SET max_parallel_workers_per_gather = 0;
SET track_io_timing = on;

SELECT
    count(*) AS total_rows,
    count(*) FILTER (
        WHERE event_id = md5('event-0')::uuid
          AND is_approved = TRUE
          AND processing_status IN ('', 'done')
          AND deleted_at IS NULL
    ) AS hot_event_visible
FROM moments;

SELECT
    created_at AS cursor_created,
    id::text AS cursor_id,
    "order" AS cursor_order,
    CASE WHEN "order" > 0 THEN 0 ELSE 1 END AS cursor_group
FROM moments
WHERE event_id = md5('event-0')::uuid
  AND is_approved = TRUE
  AND processing_status IN ('', 'done')
  AND deleted_at IS NULL
ORDER BY CASE WHEN "order" > 0 THEN 0 ELSE 1 END,
         "order", created_at DESC, id DESC
OFFSET 99 LIMIT 1
